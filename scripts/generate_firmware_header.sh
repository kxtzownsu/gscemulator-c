#!/usr/bin/env bash
set -euo pipefail

export LC_ALL=C

usage() {
  cat <<'EOF'
Usage: generate_firmware_header.sh [OPTIONS] [--chip CHIP [--bootrom PATH] [--firmware PATH]]...

Generates a C header containing one or more bundled BootROM/firmware pairs.
Without --output the header is written to stdout.

Each --chip starts a new bundle group. A group needs a BootROM and a firmware
binary. With a single group, --chip may be omitted and defaults to H1B3C.

Options:
  -c, --chip CHIP      Start a chip bundle group (e.g. H1B3C, H1C3M)
  -b, --bootrom PATH   BootROM binary for the current chip
  -f, --firmware PATH  Firmware binary for the current chip
  -o, --output PATH    Write the header to PATH instead of stdout
  -h, --help           Show this help

Example:
  generate_firmware_header.sh \
    --chip H1B3C --bootrom h1b3c/bootrom.bin --firmware h1b3c/firmware.bin \
    --chip H1C3M  --bootrom H1C3M/bootrom.bin  --firmware H1C3M/firmware.bin \
    --output include/common/bundled-firmware.h
EOF
}

die() {
  printf 'generate_firmware_header.sh: %s\n' "$*" >&2
  exit 1
}

normalize_chip() {
  local value="$1"

  [[ "$value" =~ ^[A-Za-z0-9_-]+$ ]] || die "invalid chip name: $value"
  value="$(printf '%s' "$value" | tr '[:lower:]' '[:upper:]' | tr '-' '_')"
  [[ "$value" =~ ^[A-Z_][A-Z0-9_]*$ ]] || die "invalid chip name: $value"
  printf '%s' "$value"
}

validate_file() {
  local path="$1"

  [[ -f "$path" ]] || die "not a file: $path"
  [[ -r "$path" ]] || die "not readable: $path"
  [[ -s "$path" ]] || die "file is empty: $path"
}

chips=()
bootroms=()
firmwares=()

chip=""
bootrom=""
firmware=""
group_open=0

flush_group() {
  local upper
  local existing

  [[ -n "$chip" ]] || die "missing --chip for firmware group"
  [[ -n "$bootrom" ]] || die "chip $chip is missing its BootROM binary"
  [[ -n "$firmware" ]] || die "chip $chip is missing its firmware binary"

  upper="$(normalize_chip "$chip")"

  if [[ ${#chips[@]} -gt 0 ]]; then
    for existing in "${chips[@]}"; do
      [[ "$existing" == "$upper" ]] && die "duplicate chip: $upper"
    done
  fi

  validate_file "$bootrom"
  validate_file "$firmware"

  chips+=("$upper")
  bootroms+=("$bootrom")
  firmwares+=("$firmware")

  chip=""
  bootrom=""
  firmware=""
  group_open=0
}

output=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    -c|--chip)
      [[ $# -ge 2 ]] || die "missing value for $1"
      if [[ $group_open -eq 1 ]]; then
        flush_group
      fi
      chip="$2"
      group_open=1
      shift 2
      ;;
    -b|--bootrom)
      [[ $# -ge 2 ]] || die "missing value for $1"
      if [[ $group_open -eq 0 ]]; then
        chip="H1B3C"
        group_open=1
      fi
      [[ -z "$bootrom" ]] || die "chip $chip already has a BootROM binary"
      bootrom="$2"
      shift 2
      ;;
    -f|--firmware)
      [[ $# -ge 2 ]] || die "missing value for $1"
      if [[ $group_open -eq 0 ]]; then
        chip="H1B3C"
        group_open=1
      fi
      [[ -z "$firmware" ]] || die "chip $chip already has a firmware binary"
      firmware="$2"
      shift 2
      ;;
    -o|--output)
      [[ $# -ge 2 ]] || die "missing value for $1"
      output="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    --)
      shift
      break
      ;;
    -*)
      die "unknown option: $1"
      ;;
    *)
      if [[ $group_open -eq 0 ]]; then
        chip="H1B3C"
        group_open=1
      fi
      if [[ -z "$bootrom" ]]; then
        bootrom="$1"
      elif [[ -z "$firmware" ]]; then
        firmware="$1"
      else
        die "unexpected argument: $1 (start a new group with --chip)"
      fi
      shift
      ;;
  esac
done

while [[ $# -gt 0 ]]; do
  if [[ $group_open -eq 0 ]]; then
    chip="H1B3C"
    group_open=1
  fi
  if [[ -z "$bootrom" ]]; then
    bootrom="$1"
  elif [[ -z "$firmware" ]]; then
    firmware="$1"
  else
    die "unexpected argument: $1 (start a new group with --chip)"
  fi
  shift
done

if [[ $group_open -eq 1 ]]; then
  flush_group
fi

[[ ${#chips[@]} -gt 0 ]] || die "no firmware bundles requested"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

emit_array() {
  local name="$1"
  local path="$2"

  printf 'static const uint8_t %s[] = {\n' "$name"
  od -A n -v -t x1 "$path" | awk '
    {
      for (i = 1; i <= NF; i++) {
        printf "  0x%s,", $i
        n++
        if (n % 12 == 0) printf "\n"
      }
    }
    END {
      if (n % 12 != 0) printf "\n"
    }
  '
  printf '};\n'
  printf 'static const size_t %s_len = sizeof(%s);\n\n' "$name" "$name"
}

{
  printf '#ifndef COMMON_BUNDLED_FIRMWARE_H\n'
  printf '#define COMMON_BUNDLED_FIRMWARE_H\n\n'
  printf '#include <stddef.h>\n'
  printf '#include <stdint.h>\n\n'
  printf '/* Generated by scripts/generate_firmware_header.sh. Do not edit. */\n\n'
  for i in "${!chips[@]}"; do
    emit_array "BUNDLED_${chips[$i]}_BOOTROM_BIN" "${bootroms[$i]}"
    emit_array "BUNDLED_${chips[$i]}_FIRMWARE_BIN" "${firmwares[$i]}"
  done
  printf '#endif /* COMMON_BUNDLED_FIRMWARE_H */\n'
} >"$tmp"

if [[ -n "$output" ]]; then
  [[ ! -d "$output" ]] || die "output is a directory: $output"
  mkdir -p "$(dirname -- "$output")"
  chmod 644 "$tmp"
  mv -- "$tmp" "$output"
  trap - EXIT
else
  cat -- "$tmp"
fi
