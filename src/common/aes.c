static const uint8_t aes_rcon[10] = {
  0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36,
};

static uint8_t aes_xtime(uint8_t value) {
  return (uint8_t)((value << 1) ^ ((value & 0x80u) != 0 ? 0x1Bu : 0));
}

static uint8_t aes_mul(uint8_t left, uint8_t right) {
  uint8_t result = 0;
  unsigned i;

  for (i = 0; i < 8; i++) {
    if ((right & 1u) != 0) result ^= left;
    left = aes_xtime(left);
    right >>= 1;
  }

  return result;
}

static void aes_sub_word(uint8_t word[4]) {
  unsigned i;

  for (i = 0; i < 4; i++) word[i] = aes_sbox[word[i]];
}

static void aes_rot_word(uint8_t word[4]) {
  uint8_t first = word[0];

  word[0] = word[1];
  word[1] = word[2];
  word[2] = word[3];
  word[3] = first;
}

bool aes_init(AesContext *ctx, const uint8_t *key, size_t key_len) {
  uint8_t word[4];
  unsigned total_words;
  unsigned i;

  if (ctx == NULL || key == NULL) return false;
  if (key_len != 16 && key_len != 24 && key_len != 32) return false;

  ctx->key_words = (unsigned)(key_len / 4);
  ctx->rounds = ctx->key_words + 6;
  total_words = 4 * (ctx->rounds + 1);

  memcpy(ctx->round_keys, key, key_len);

  for (i = ctx->key_words; i < total_words; i++) {
    memcpy(word, &ctx->round_keys[(i - 1) * 4], sizeof(word));

    if (i % ctx->key_words == 0) {
      aes_rot_word(word);
      aes_sub_word(word);
      word[0] ^= aes_rcon[i / ctx->key_words - 1];
    } else if (ctx->key_words > 6 && i % ctx->key_words == 4) {
      aes_sub_word(word);
    }

    ctx->round_keys[i * 4 + 0] = ctx->round_keys[(i - ctx->key_words) * 4 + 0] ^ word[0];
    ctx->round_keys[i * 4 + 1] = ctx->round_keys[(i - ctx->key_words) * 4 + 1] ^ word[1];
    ctx->round_keys[i * 4 + 2] = ctx->round_keys[(i - ctx->key_words) * 4 + 2] ^ word[2];
    ctx->round_keys[i * 4 + 3] = ctx->round_keys[(i - ctx->key_words) * 4 + 3] ^ word[3];
  }

  return true;
}

static void aes_add_round_key(uint8_t state[16], const uint8_t *round_key) {
  unsigned i;

  for (i = 0; i < 16; i++) state[i] ^= round_key[i];
}

static void aes_shift_rows(uint8_t state[16]) {
  uint8_t copy[16];

  memcpy(copy, state, sizeof(copy));
  state[0] = copy[0];
  state[4] = copy[4];
  state[8] = copy[8];
  state[12] = copy[12];
  state[1] = copy[5];
  state[5] = copy[9];
  state[9] = copy[13];
  state[13] = copy[1];
  state[2] = copy[10];
  state[6] = copy[14];
  state[10] = copy[2];
  state[14] = copy[6];
  state[3] = copy[15];
  state[7] = copy[3];
  state[11] = copy[7];
  state[15] = copy[11];
}

static void aes_inv_shift_rows(uint8_t state[16]) {
  uint8_t copy[16];

  memcpy(copy, state, sizeof(copy));
  state[0] = copy[0];
  state[4] = copy[4];
  state[8] = copy[8];
  state[12] = copy[12];
  state[1] = copy[13];
  state[5] = copy[1];
  state[9] = copy[5];
  state[13] = copy[9];
  state[2] = copy[10];
  state[6] = copy[14];
  state[10] = copy[2];
  state[14] = copy[6];
  state[3] = copy[7];
  state[7] = copy[11];
  state[11] = copy[15];
  state[15] = copy[3];
}

static void aes_mix_columns(uint8_t state[16]) {
  unsigned column;

  for (column = 0; column < 4; column++) {
    uint8_t *s = &state[column * 4];
    uint8_t a0 = s[0], a1 = s[1], a2 = s[2], a3 = s[3];

    s[0] = (uint8_t)(aes_xtime(a0) ^ (aes_xtime(a1) ^ a1) ^ a2 ^ a3);
    s[1] = (uint8_t)(a0 ^ aes_xtime(a1) ^ (aes_xtime(a2) ^ a2) ^ a3);
    s[2] = (uint8_t)(a0 ^ a1 ^ aes_xtime(a2) ^ (aes_xtime(a3) ^ a3));
    s[3] = (uint8_t)((aes_xtime(a0) ^ a0) ^ a1 ^ a2 ^ aes_xtime(a3));
  }
}

static void aes_inv_mix_columns(uint8_t state[16]) {
  unsigned column;

  for (column = 0; column < 4; column++) {
    uint8_t *s = &state[column * 4];
    uint8_t a0 = s[0], a1 = s[1], a2 = s[2], a3 = s[3];

    s[0] = (uint8_t)(aes_mul(a0, 0x0E) ^ aes_mul(a1, 0x0B) ^ aes_mul(a2, 0x0D) ^
                     aes_mul(a3, 0x09));
    s[1] = (uint8_t)(aes_mul(a0, 0x09) ^ aes_mul(a1, 0x0E) ^ aes_mul(a2, 0x0B) ^
                     aes_mul(a3, 0x0D));
    s[2] = (uint8_t)(aes_mul(a0, 0x0D) ^ aes_mul(a1, 0x09) ^ aes_mul(a2, 0x0E) ^
                     aes_mul(a3, 0x0B));
    s[3] = (uint8_t)(aes_mul(a0, 0x0B) ^ aes_mul(a1, 0x0D) ^ aes_mul(a2, 0x09) ^
                     aes_mul(a3, 0x0E));
  }
}

void aes_encrypt_block(const AesContext *ctx, const uint8_t in[AES_BLOCK_SIZE],
                       uint8_t out[AES_BLOCK_SIZE]) {
  uint8_t state[16];
  unsigned round;
  unsigned i;

  memcpy(state, in, sizeof(state));
  aes_add_round_key(state, ctx->round_keys);

  for (round = 1; round < ctx->rounds; round++) {
    for (i = 0; i < 16; i++) state[i] = aes_sbox[state[i]];
    aes_shift_rows(state);
    aes_mix_columns(state);
    aes_add_round_key(state, &ctx->round_keys[round * 16]);
  }

  for (i = 0; i < 16; i++) state[i] = aes_sbox[state[i]];
  aes_shift_rows(state);
  aes_add_round_key(state, &ctx->round_keys[ctx->rounds * 16]);

  memcpy(out, state, sizeof(state));
}

void aes_decrypt_block(const AesContext *ctx, const uint8_t in[AES_BLOCK_SIZE],
                       uint8_t out[AES_BLOCK_SIZE]) {
  uint8_t state[16];
  unsigned round;
  unsigned i;

  memcpy(state, in, sizeof(state));
  aes_add_round_key(state, &ctx->round_keys[ctx->rounds * 16]);

  for (round = ctx->rounds - 1; round > 0; round--) {
    aes_inv_shift_rows(state);
    for (i = 0; i < 16; i++) state[i] = aes_inv_sbox[state[i]];
    aes_add_round_key(state, &ctx->round_keys[round * 16]);
    aes_inv_mix_columns(state);
  }

  aes_inv_shift_rows(state);
  for (i = 0; i < 16; i++) state[i] = aes_inv_sbox[state[i]];
  aes_add_round_key(state, ctx->round_keys);

  memcpy(out, state, sizeof(state));
}
