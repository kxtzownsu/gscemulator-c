#ifndef H1B3C_PERIPHERALS_GLOBALSEC_H
#define H1B3C_PERIPHERALS_GLOBALSEC_H

#include <common/peripherals/component.h>

#define REG_GLOBALSEC_BASE_ADDR 0x40090000
#define REG_GLOBALSEC_REGION_OFFSET 0x0
#define REG_GLOBALSEC_REGION_COUNT 0xB4
#define REG_GLOBALSEC_CPU0_S_PERMISSION_OFFSET 0x2D0
#define REG_GLOBALSEC_CPU0_S_DAP_PERMISSION_OFFSET 0x2D4
#define REG_GLOBALSEC_DDMA0_PERMISSION_OFFSET 0x2D8
#define REG_GLOBALSEC_SOFTWARE_LVL_OFFSET 0x2DC
#define REG_GLOBALSEC_PERMISSION_COUNT 4
#define REG_GLOBALSEC_OBFS_SW_EN_OFFSET 0x40B8
#define REG_GLOBALSEC_HIDE_ROM_OFFSET 0x40D0
#define REG_GLOBALSEC_DUMMYKEY0_OFFSET 0x9598
#define REG_GLOBALSEC_DBG_CONTROL_OFFSET 0xA6D0
#define REG_GLOBALSEC_DUMMYKEY1_OFFSET 0xAF04
#define REG_GLOBALSEC_DUMMYKEY2_OFFSET 0xB2AC
#define REG_GLOBALSEC_SB_COMP_STATUS_OFFSET 0x1000
#define REG_GLOBALSEC_SB_BL_SIG0_OFFSET 0x1004
#define REG_GLOBALSEC_SB_BL_SIG_COUNT 8
#define REG_GLOBALSEC_SIG_UNLOCK_OFFSET 0x1024
#define REG_GLOBALSEC_ALERT_CFG_LOCK_OFFSET 0x102C
#define REG_GLOBALSEC_ALERT_FW_TRIGGER_OFFSET 0x4000
#define REG_GLOBALSEC_ALERT_INTR_STS0_OFFSET 0x4004
#define REG_GLOBALSEC_ALERT_INTR_STS1_OFFSET 0x4008
#define REG_GLOBALSEC_ALERT_NMI_EN0_OFFSET 0x400C
#define REG_GLOBALSEC_ALERT_NMI_EN1_OFFSET 0x4010
#define REG_GLOBALSEC_ALERT_GROUPA_EN0_OFFSET 0x4014
#define REG_GLOBALSEC_ALERT_GROUPA_EN1_OFFSET 0x4018
#define REG_GLOBALSEC_ALERT_GROUPB_EN0_OFFSET 0x401C
#define REG_GLOBALSEC_ALERT_GROUPB_EN1_OFFSET 0x4020
#define REG_GLOBALSEC_ALERT_GROUPC_EN0_OFFSET 0x4024
#define REG_GLOBALSEC_ALERT_GROUPC_EN1_OFFSET 0x4028
#define REG_GLOBALSEC_ALERT_DLYCTR0_EN0_OFFSET 0x402C
#define REG_GLOBALSEC_ALERT_DLYCTR0_EN1_OFFSET 0x4030
#define REG_GLOBALSEC_ALERT_DLYCTR1_EN0_OFFSET 0x4034
#define REG_GLOBALSEC_ALERT_DLYCTR1_EN1_OFFSET 0x4038
#define REG_GLOBALSEC_ALERT_DLYCTR2_EN0_OFFSET 0x403C
#define REG_GLOBALSEC_ALERT_DLYCTR2_EN1_OFFSET 0x4040
#define REG_GLOBALSEC_ALERT_GROUPA_CTR_OFFSET 0x4044
#define REG_GLOBALSEC_ALERT_GROUPB_CTR_OFFSET 0x4048
#define REG_GLOBALSEC_ALERT_GROUPC_CTR_OFFSET 0x404C
#define REG_GLOBALSEC_ALERT_GROUPA_THRESHOLD_OFFSET 0x4050
#define REG_GLOBALSEC_ALERT_GROUPB_THRESHOLD_OFFSET 0x4054
#define REG_GLOBALSEC_ALERT_GROUPC_THRESHOLD_OFFSET 0x4058
#define REG_GLOBALSEC_ALERT_CONTROL_OFFSET 0x405C
#define REG_GLOBALSEC_ALERT_DLYCTR0_OFFSET 0x4060
#define REG_GLOBALSEC_ALERT_DLYCTR1_OFFSET 0x4064
#define REG_GLOBALSEC_ALERT_DLYCTR2_OFFSET 0x4068
#define REG_GLOBALSEC_ALERT_DLYCTR0_LEN_OFFSET 0x406C
#define REG_GLOBALSEC_ALERT_DLYCTR1_LEN_OFFSET 0x4070
#define REG_GLOBALSEC_ALERT_DLYCTR2_LEN_OFFSET 0x4074
#define REG_GLOBALSEC_ALERT_DLYCTR0_SHUTDOWN_EN_OFFSET 0x4078
#define REG_GLOBALSEC_ALERT_DLYCTR1_SHUTDOWN_EN_OFFSET 0x407C
#define REG_GLOBALSEC_ALERT_DLYCTR2_SHUTDOWN_EN_OFFSET 0x4080
#define REG_GLOBALSEC_ALERT_DLYCTR0_CLEAR_OFFSET 0x4084
#define REG_GLOBALSEC_ALERT_DLYCTR1_CLEAR_OFFSET 0x4088
#define REG_GLOBALSEC_ALERT_DLYCTR2_CLEAR_OFFSET 0x408C
#define REG_GLOBALSEC_ALERT_COUNT 44

_Static_assert(REG_GLOBALSEC_REGION_OFFSET + REG_GLOBALSEC_REGION_COUNT * 4 <=
                   REG_GLOBALSEC_CPU0_S_PERMISSION_OFFSET,
               "GLOBALSEC region window overlaps the permission registers");
_Static_assert(REG_GLOBALSEC_SB_BL_SIG0_OFFSET + REG_GLOBALSEC_SB_BL_SIG_COUNT * 4 <=
                   REG_GLOBALSEC_SIG_UNLOCK_OFFSET,
               "SB_BL_SIG overlaps SIG_UNLOCK");

Component *GLOBALSEC_Initialize(void);
void GLOBALSEC_Poll(void);

#endif /* H1B3C_PERIPHERALS_GLOBALSEC_H */
