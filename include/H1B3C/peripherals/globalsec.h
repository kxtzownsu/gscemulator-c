#ifndef H1B3C_PERIPHERALS_GLOBALSEC_H
#define H1B3C_PERIPHERALS_GLOBALSEC_H

#include <common/peripherals/component.h>

#define REG_GLOBALSEC_BASE_ADDR 0x40090000
#define REG_GLOBALSEC_REGION_OFFSET 0x0
#define REG_GLOBALSEC_REGION_COUNT 0xB4
#define REG_GLOBALSEC_CPU0_S_PERMISSION_OFFSET 0x2D0
#define REG_GLOBALSEC_CPU0_S_DAP_PERMISSION_OFFSET 0x2D4
#define REG_GLOBALSEC_DDMA0_PERMISSION_OFFSET 0x2D8
#define REG_GLOBALSEC_SOFTWARE_LVL_OFFSET 0x2DC
#define REG_GLOBALSEC_PERMISSION_COUNT 4
#define REG_GLOBALSEC_ALERT_INTR_STS0_OFFSET 0x4004
#define REG_GLOBALSEC_ALERT_INTR_STS1_OFFSET 0x4008
#define REG_GLOBALSEC_ALERT_CONTROL_OFFSET 0x405C
#define REG_GLOBALSEC_OBFS_SW_EN_OFFSET 0x40B8
#define REG_GLOBALSEC_HIDE_ROM_OFFSET 0x40D0
#define REG_GLOBALSEC_DUMMYKEY0_OFFSET 0x9598
#define REG_GLOBALSEC_DBG_CONTROL_OFFSET 0xA6D0
#define REG_GLOBALSEC_DUMMYKEY1_OFFSET 0xAF04
#define REG_GLOBALSEC_DUMMYKEY2_OFFSET 0xB2AC
#define REG_GLOBALSEC_SB_COMP_STATUS_OFFSET 0x1000
#define REG_GLOBALSEC_SB_BL_SIG0_OFFSET 0x1004
#define REG_GLOBALSEC_SB_BL_SIG_COUNT 8
#define REG_GLOBALSEC_SIG_UNLOCK_OFFSET 0x1024

_Static_assert(REG_GLOBALSEC_REGION_OFFSET + REG_GLOBALSEC_REGION_COUNT * 4 <=
                   REG_GLOBALSEC_CPU0_S_PERMISSION_OFFSET,
               "GLOBALSEC region window overlaps the permission registers");
_Static_assert(REG_GLOBALSEC_SB_BL_SIG0_OFFSET + REG_GLOBALSEC_SB_BL_SIG_COUNT * 4 <=
                   REG_GLOBALSEC_SIG_UNLOCK_OFFSET,
               "SB_BL_SIG overlaps SIG_UNLOCK");

Component *GLOBALSEC_Initialize(void);

#endif /* H1B3C_PERIPHERALS_GLOBALSEC_H */
