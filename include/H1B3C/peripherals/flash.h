#ifndef H1B3C_PERIPHERALS_FLASH_H
#define H1B3C_PERIPHERALS_FLASH_H

#include <common/peripherals/component.h>

#define REG_FLASH_BASE_ADDR 0x40720000
#define REG_FLASH_PE_CONTROL0_OFFSET 0x0
#define REG_FLASH_PE_CONTROL1_OFFSET 0x4
#define REG_FLASH_TRANS_OFFSET 0x8
#define REG_FLASH_PROTECT_INFO1_ERASE_OFFSET 0xC
#define REG_FLASH_DOUT_VAL0_OFFSET 0x3C
#define REG_FLASH_DOUT_VAL1_OFFSET 0x40
#define REG_FLASH_WR_DATA0_OFFSET 0x48
#define REG_FLASH_WR_DATA_COUNT 32
#define REG_FLASH_PE_EN_OFFSET 0xC8
#define REG_FLASH_ERROR_OFFSET 0xD4
#define REG_FLASH_TIMING_PROG_SMART_ALGO_ON_OFFSET 0x104
#define REG_FLASH_TIMING_ERASE_SMART_ALGO_ON_OFFSET 0x134
#define REG_FLASH_TIMING_BULKERASE_SMART_ALGO_ON_OFFSET 0x154

_Static_assert(REG_FLASH_WR_DATA0_OFFSET + REG_FLASH_WR_DATA_COUNT * 4 <=
                   REG_FLASH_PE_EN_OFFSET,
               "FLASH WR_DATA overlaps PE_EN");

Component *FLASH_Initialize(void);

#endif /* H1B3C_PERIPHERALS_FLASH_H */
