#ifndef H1B3C_PERIPHERALS_KEYMGR_H
#define H1B3C_PERIPHERALS_KEYMGR_H

#include <common/peripherals/component.h>

#define REG_KEYMGR_BASE_ADDR 0x40570000
#define REG_KEYMGR_HKEY_RWR0_OFFSET 0x3000
#define REG_KEYMGR_HKEY_RWR_COUNT 8
#define REG_KEYMGR_RWR_VLD_OFFSET 0x3020
#define REG_KEYMGR_RWR_LOCK_OFFSET 0x3024
#define REG_KEYMGR_HKEY_ERR_FLAGS_OFFSET 0x3324
#define REG_KEYMGR_SHA_CFG_MSGLEN_LO_OFFSET 0x400
#define REG_KEYMGR_SHA_CFG_MSGLEN_HI_OFFSET 0x404
#define REG_KEYMGR_SHA_CFG_EN_OFFSET 0x408
#define REG_KEYMGR_SHA_CFG_WR_EN_OFFSET 0x40C
#define REG_KEYMGR_SHA_TRIG_OFFSET 0x410
#define REG_KEYMGR_SHA_INPUT_FIFO_OFFSET 0x440
#define REG_KEYMGR_SHA_STS_H0_OFFSET 0x444
#define REG_KEYMGR_SHA_STS_H_COUNT 8
#define REG_KEYMGR_SHA_KEY_W0_OFFSET 0x464
#define REG_KEYMGR_SHA_KEY_W_COUNT 8
#define REG_KEYMGR_SHA_STS_OFFSET 0x484
#define REG_KEYMGR_SHA_ITCR_OFFSET 0x488
#define REG_KEYMGR_SHA_ITOP_OFFSET 0x48C
#define REG_KEYMGR_SHA_USE_HIDDEN_KEY_OFFSET 0x490
#define REG_KEYMGR_SHA_USE_CERT_OFFSET 0x494
#define REG_KEYMGR_SHA_CERT_OVERRIDE_OFFSET 0x498
#define REG_KEYMGR_SHA_RAND_STALL_CTL_OFFSET 0x49C
#define REG_KEYMGR_SHA_EXECUTE_COUNT_STATE_OFFSET 0x4A0
#define REG_KEYMGR_SHA_EXECUTE_COUNT_MAX_OFFSET 0x4A4
#define REG_KEYMGR_CERT_REVOKES_CTRL_OFFSET 0x4A8

_Static_assert(REG_KEYMGR_HKEY_RWR0_OFFSET + REG_KEYMGR_HKEY_RWR_COUNT * 4 <=
                   REG_KEYMGR_RWR_VLD_OFFSET,
               "HKEY_RWR overlaps RWR_VLD");
_Static_assert(REG_KEYMGR_SHA_STS_H0_OFFSET + REG_KEYMGR_SHA_STS_H_COUNT * 4 <=
                   REG_KEYMGR_SHA_KEY_W0_OFFSET,
               "SHA_STS_H overlaps SHA_KEY_W");
_Static_assert(REG_KEYMGR_SHA_KEY_W0_OFFSET + REG_KEYMGR_SHA_KEY_W_COUNT * 4 <=
                   REG_KEYMGR_SHA_STS_OFFSET,
               "SHA_KEY_W overlaps SHA_STS");

Component *KEYMGR_Initialize(void);

#endif /* H1B3C_PERIPHERALS_KEYMGR_H */
