#ifndef H1B3C_PERIPHERALS_KEYMGR_H
#define H1B3C_PERIPHERALS_KEYMGR_H

#include <common/peripherals/component.h>

#define REG_KEYMGR_BASE_ADDR 0x40570000
#define REG_KEYMGR_AES_CTRL_OFFSET 0x0
#define REG_KEYMGR_AES_WFIFO_DATA_OFFSET 0x8
#define REG_KEYMGR_AES_RFIFO_DATA_OFFSET 0xC
#define REG_KEYMGR_AES_KEY0_OFFSET 0x2C
#define REG_KEYMGR_AES_KEY_COUNT 8
#define REG_KEYMGR_AES_KEY_START_OFFSET 0x4C
#define REG_KEYMGR_AES_CTR0_OFFSET 0x50
#define REG_KEYMGR_AES_CTR_COUNT 4
#define REG_KEYMGR_AES_RAND_STALL_CTL_OFFSET 0x60
#define REG_KEYMGR_AES_WFIFO_LEVEL_OFFSET 0x64
#define REG_KEYMGR_AES_WFIFO_FULL_OFFSET 0x68
#define REG_KEYMGR_AES_RFIFO_LEVEL_OFFSET 0x6C
#define REG_KEYMGR_AES_RFIFO_EMPTY_OFFSET 0x70
#define REG_KEYMGR_AES_EXECUTE_COUNT_STATE_OFFSET 0x74
#define REG_KEYMGR_AES_EXECUTE_COUNT_MAX_OFFSET 0x78
#define REG_KEYMGR_GCM_DO_ACC_OFFSET 0x7C
#define REG_KEYMGR_GCM_H0_OFFSET 0x80
#define REG_KEYMGR_GCM_H_COUNT 4
#define REG_KEYMGR_GCM_MAC0_OFFSET 0x90
#define REG_KEYMGR_GCM_MAC_COUNT 4
#define REG_KEYMGR_GCM_HASH_IN0_OFFSET 0xA0
#define REG_KEYMGR_GCM_HASH_IN_COUNT 4
#define REG_KEYMGR_AES_WIPE_SECRETS_OFFSET 0xB0
#define REG_KEYMGR_AES_INT_ENABLE_OFFSET 0xB4
#define REG_KEYMGR_AES_INT_STATE_OFFSET 0xB8
#define REG_KEYMGR_AES_INT_TEST_OFFSET 0xBC
#define REG_KEYMGR_AES_USE_HIDDEN_KEY_OFFSET 0xC0
#define REG_KEYMGR_HKEY_RWR0_OFFSET 0x3000
#define REG_KEYMGR_HKEY_RWR_COUNT 8
#define REG_KEYMGR_RWR_VLD_OFFSET 0x3020
#define REG_KEYMGR_RWR_LOCK_OFFSET 0x3024
#define REG_KEYMGR_HKEY_FWR0_OFFSET 0x3100
#define REG_KEYMGR_HKEY_FWR_COUNT 8
#define REG_KEYMGR_FWR_VLD_OFFSET 0x3120
#define REG_KEYMGR_FW_MAJOR_VERSION_OFFSET 0x3124
#define REG_KEYMGR_FWR_LOCK_OFFSET 0x3128
#define REG_KEYMGR_HKEY_FRR0_OFFSET 0x3300
#define REG_KEYMGR_HKEY_FRR_COUNT 8
#define REG_KEYMGR_HKEY_ERR_FLAGS_OFFSET 0x3324
#define REG_KEYMGR_SHA_CFG_MSGLEN_LO_OFFSET 0x400
#define REG_KEYMGR_SHA_CFG_MSGLEN_HI_OFFSET 0x404
#define REG_KEYMGR_SHA_CFG_EN_OFFSET 0x408
#define REG_KEYMGR_SHA_CFG_WR_EN_OFFSET 0x40C
#define REG_KEYMGR_SHA_TRIG_OFFSET 0x410
#define REG_KEYMGR_SHA_INPUT_FIFO_OFFSET 0x440
#define REG_KEYMGR_SHA_STS_H0_OFFSET 0x444
#define REG_KEYMGR_SHA_STS_H_COUNT 8
#define REG_KEYMGR_SHA_KEY_W0_OFFSET 0x464
#define REG_KEYMGR_SHA_KEY_W_COUNT 8
#define REG_KEYMGR_SHA_STS_OFFSET 0x484
#define REG_KEYMGR_SHA_ITCR_OFFSET 0x488
#define REG_KEYMGR_SHA_ITOP_OFFSET 0x48C
#define REG_KEYMGR_SHA_USE_HIDDEN_KEY_OFFSET 0x490
#define REG_KEYMGR_SHA_USE_CERT_OFFSET 0x494
#define REG_KEYMGR_SHA_CERT_OVERRIDE_OFFSET 0x498
#define REG_KEYMGR_SHA_RAND_STALL_CTL_OFFSET 0x49C
#define REG_KEYMGR_SHA_EXECUTE_COUNT_STATE_OFFSET 0x4A0
#define REG_KEYMGR_SHA_EXECUTE_COUNT_MAX_OFFSET 0x4A4
#define REG_KEYMGR_CERT_REVOKE_CTRL0_OFFSET 0x4A8
#define REG_KEYMGR_CERT_REVOKE_CTRL1_OFFSET 0x4AC
#define REG_KEYMGR_CERT_REVOKE_CTRL2_OFFSET 0x4B0
#define REG_KEYMGR_CERT_REVOKE_CTRL_COUNT 3

_Static_assert(REG_KEYMGR_AES_KEY0_OFFSET + REG_KEYMGR_AES_KEY_COUNT * 4 <=
                   REG_KEYMGR_AES_KEY_START_OFFSET,
               "AES_KEY overlaps AES_KEY_START");
_Static_assert(REG_KEYMGR_AES_CTR0_OFFSET + REG_KEYMGR_AES_CTR_COUNT * 4 <=
                   REG_KEYMGR_AES_RAND_STALL_CTL_OFFSET,
               "AES_CTR overlaps AES_RAND_STALL_CTL");
_Static_assert(REG_KEYMGR_GCM_H0_OFFSET + REG_KEYMGR_GCM_H_COUNT * 4 <=
                   REG_KEYMGR_GCM_MAC0_OFFSET,
               "GCM_H overlaps GCM_MAC");
_Static_assert(REG_KEYMGR_GCM_MAC0_OFFSET + REG_KEYMGR_GCM_MAC_COUNT * 4 <=
                   REG_KEYMGR_GCM_HASH_IN0_OFFSET,
               "GCM_MAC overlaps GCM_HASH_IN");
_Static_assert(REG_KEYMGR_GCM_HASH_IN0_OFFSET + REG_KEYMGR_GCM_HASH_IN_COUNT * 4 <=
                   REG_KEYMGR_AES_WIPE_SECRETS_OFFSET,
               "GCM_HASH_IN overlaps AES_WIPE_SECRETS");
_Static_assert(REG_KEYMGR_HKEY_RWR0_OFFSET + REG_KEYMGR_HKEY_RWR_COUNT * 4 <=
                   REG_KEYMGR_RWR_VLD_OFFSET,
               "HKEY_RWR overlaps RWR_VLD");
_Static_assert(REG_KEYMGR_HKEY_FWR0_OFFSET + REG_KEYMGR_HKEY_FWR_COUNT * 4 <=
                   REG_KEYMGR_FWR_VLD_OFFSET,
               "HKEY_FWR overlaps FWR_VLD");
_Static_assert(REG_KEYMGR_FWR_VLD_OFFSET + 4 <= REG_KEYMGR_FW_MAJOR_VERSION_OFFSET,
               "FWR_VLD overlaps FW_MAJOR_VERSION");
_Static_assert(REG_KEYMGR_FW_MAJOR_VERSION_OFFSET + 4 <= REG_KEYMGR_FWR_LOCK_OFFSET,
               "FW_MAJOR_VERSION overlaps FWR_LOCK");
_Static_assert(REG_KEYMGR_FWR_LOCK_OFFSET + 4 <= REG_KEYMGR_HKEY_FRR0_OFFSET,
               "FWR_LOCK overlaps HKEY_FRR");
_Static_assert(REG_KEYMGR_HKEY_FRR0_OFFSET + REG_KEYMGR_HKEY_FRR_COUNT * 4 <=
                   REG_KEYMGR_HKEY_ERR_FLAGS_OFFSET,
               "HKEY_FRR overlaps HKEY_ERR_FLAGS");
_Static_assert(REG_KEYMGR_SHA_STS_H0_OFFSET + REG_KEYMGR_SHA_STS_H_COUNT * 4 <=
                   REG_KEYMGR_SHA_KEY_W0_OFFSET,
               "SHA_STS_H overlaps SHA_KEY_W");
_Static_assert(REG_KEYMGR_SHA_KEY_W0_OFFSET + REG_KEYMGR_SHA_KEY_W_COUNT * 4 <=
                   REG_KEYMGR_SHA_STS_OFFSET,
               "SHA_KEY_W overlaps SHA_STS");

Component *KEYMGR_Initialize(void);

#endif /* H1B3C_PERIPHERALS_KEYMGR_H */
