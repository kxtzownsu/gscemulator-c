#ifndef H1B3C_PERIPHERALS_TIMELS_H
#define H1B3C_PERIPHERALS_TIMELS_H

#include <common/peripherals/component.h>

#define REG_TIMELS_BASE_ADDR 0x40540000
#define REG_TIMELS_TIMER0_CONTROL_OFFSET 0x0
#define REG_TIMELS_TIMER0_STATUS_OFFSET 0x4
#define REG_TIMELS_TIMER0_LOAD_OFFSET 0x8
#define REG_TIMELS_TIMER0_RELOADVAL_OFFSET 0xC
#define REG_TIMELS_TIMER0_VALUE_OFFSET 0x10
#define REG_TIMELS_TIMER0_STEP_OFFSET 0x14
#define REG_TIMELS_TIMER0_IER_OFFSET 0x18
#define REG_TIMELS_TIMER0_ISR_OFFSET 0x1C
#define REG_TIMELS_TIMER0_IPR_OFFSET 0x20
#define REG_TIMELS_TIMER0_IAR_OFFSET 0x24
#define REG_TIMELS_TIMER0_WAKEUP_ACK_OFFSET 0x28
#define REG_TIMELS_TIMER1_CONTROL_OFFSET 0x40
#define REG_TIMELS_TIMER1_STATUS_OFFSET 0x44
#define REG_TIMELS_TIMER1_LOAD_OFFSET 0x48
#define REG_TIMELS_TIMER1_RELOADVAL_OFFSET 0x4C
#define REG_TIMELS_TIMER1_VALUE_OFFSET 0x50
#define REG_TIMELS_TIMER1_STEP_OFFSET 0x54
#define REG_TIMELS_TIMER1_IER_OFFSET 0x58
#define REG_TIMELS_TIMER1_ISR_OFFSET 0x5C
#define REG_TIMELS_TIMER1_IPR_OFFSET 0x60
#define REG_TIMELS_TIMER1_IAR_OFFSET 0x64
#define REG_TIMELS_TIMER1_WAKEUP_ACK_OFFSET 0x68
#define REG_TIMELS_ITCR_OFFSET 0xF00
#define REG_TIMELS_ITOP_OFFSET 0xF04

#define REG_TIMELS_TIMER_CONTROL_OFFSET 0x0
#define REG_TIMELS_TIMER_STATUS_OFFSET 0x4
#define REG_TIMELS_TIMER_LOAD_OFFSET 0x8
#define REG_TIMELS_TIMER_RELOADVAL_OFFSET 0xC
#define REG_TIMELS_TIMER_VALUE_OFFSET 0x10
#define REG_TIMELS_TIMER_STEP_OFFSET 0x14
#define REG_TIMELS_TIMER_IER_OFFSET 0x18
#define REG_TIMELS_TIMER_ISR_OFFSET 0x1C
#define REG_TIMELS_TIMER_IPR_OFFSET 0x20
#define REG_TIMELS_TIMER_IAR_OFFSET 0x24
#define REG_TIMELS_TIMER_WAKEUP_ACK_OFFSET 0x28

_Static_assert(REG_TIMELS_TIMER0_CONTROL_OFFSET + REG_TIMELS_TIMER_WAKEUP_ACK_OFFSET + 4 <=
                   REG_TIMELS_TIMER1_CONTROL_OFFSET,
               "TIMER0 overlaps TIMER1");
_Static_assert(REG_TIMELS_TIMER1_WAKEUP_ACK_OFFSET + 4 <= REG_TIMELS_ITCR_OFFSET,
               "TIMER1 overlaps ITCR");

Component *TIMELS_Initialize(void);
void TIMELS_Poll(void);

#endif /* H1B3C_PERIPHERALS_TIMELS_H */
