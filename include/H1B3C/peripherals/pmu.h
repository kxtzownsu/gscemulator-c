#ifndef H1B3C_PERIPHERALS_PMU_H
#define H1B3C_PERIPHERALS_PMU_H

#include <common/peripherals/component.h>

#define REG_PMU_BASE_ADDR 0x40000000
#define REG_PMU_LENGTH 0x20000
#define REG_PMU_CLRRST_OFFSET 0x8
#define REG_PMU_SW_PDB_OFFSET 0x30
#define REG_PMU_SW_PDB_SECURE_OFFSET 0x34
#define REG_PMU_LOW_POWER_DIS_OFFSET 0x14
#define REG_PMU_EXITPD_MASK_OFFSET 0x4C
#define REG_PMU_RSTSRC_OFFSET 0xC
#define REG_PMU_PERICLKSET0_OFFSET 0x64
#define REG_PMU_PERICLKCLR0_OFFSET 0x68
#define REG_PMU_PERICLKSET1_OFFSET 0x6C
#define REG_PMU_PERICLKCLR1_OFFSET 0x70
#define REG_PMU_RST_WR_EN_OFFSET 0x90
#define REG_PMU_RST_WR_EN_COUNT 2
#define REG_PMU_RST_OFFSET 0x94
#define REG_PMU_RST_COUNT 2
#define REG_PMU_LONG_LIFE_SCRATCH_WR_EN_OFFSET 0x128
#define REG_PMU_LONG_LIFE_SCRATCH_OFFSET 0x12C
#define REG_PMU_LONG_LIFE_SCRATCH_COUNT 4
#define REG_PMU_PWRDN_SCRATCH_OFFSET 0xA0
#define REG_PMU_PWRDN_SCRATCH_COUNT 32
#define REG_PMU_PWRDN_SCRATCH_LOCK_OFFSET 0x120
#define REG_PMU_PWRDN_SCRATCH_LOCK_COUNT 2
#define REG_PMU_INT_ENABLE_OFFSET 0x13C
#define REG_PMU_CHIP_ID_OFFSET 0x1FFF8

_Static_assert(REG_PMU_RST_WR_EN_OFFSET + 4 <= REG_PMU_RST_OFFSET,
               "PMU RST_WR_EN overlaps RST");
_Static_assert(REG_PMU_RST_OFFSET + 4 <= REG_PMU_PWRDN_SCRATCH_OFFSET,
               "PMU RST overlaps PWRDN_SCRATCH");
_Static_assert(REG_PMU_PWRDN_SCRATCH_OFFSET + REG_PMU_PWRDN_SCRATCH_COUNT * 4 <=
                   REG_PMU_PWRDN_SCRATCH_LOCK_OFFSET,
               "PMU PWRDN_SCRATCH overlaps PWRDN_SCRATCH_LOCK");
_Static_assert(REG_PMU_PWRDN_SCRATCH_LOCK_OFFSET + REG_PMU_PWRDN_SCRATCH_LOCK_COUNT * 4 <=
                   REG_PMU_LONG_LIFE_SCRATCH_WR_EN_OFFSET,
               "PMU PWRDN_SCRATCH_LOCK overlaps LONG_LIFE_SCRATCH_WR_EN");
_Static_assert(REG_PMU_LONG_LIFE_SCRATCH_WR_EN_OFFSET + 4 <=
                   REG_PMU_LONG_LIFE_SCRATCH_OFFSET,
               "PMU LONG_LIFE_SCRATCH_WR_EN overlaps LONG_LIFE_SCRATCH");
_Static_assert(REG_PMU_LONG_LIFE_SCRATCH_OFFSET + REG_PMU_LONG_LIFE_SCRATCH_COUNT * 4 <=
                   REG_PMU_INT_ENABLE_OFFSET,
               "PMU LONG_LIFE_SCRATCH overlaps INT_ENABLE");

Component *PMU_Initialize(void);

#endif /* H1B3C_PERIPHERALS_PMU_H */
