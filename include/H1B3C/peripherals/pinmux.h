#ifndef H1B3C_PERIPHERALS_PINMUX_H
#define H1B3C_PERIPHERALS_PINMUX_H

#include <common/peripherals/component.h>

#define REG_PINMUX_BASE_ADDR 0x40060000
#define REG_PINMUX_REG_COUNT 0xA5

#define REG_PINMUX_PAD_SEL_END_OFFSET 0xF4
#define REG_PINMUX_GPIO0_SEL_OFFSET 0xF8
#define REG_PINMUX_GPIO1_SEL_OFFSET 0x138
#define REG_PINMUX_GPIO_SEL_COUNT 16
#define REG_PINMUX_OTHER_SEL_OFFSET 0x178
#define REG_PINMUX_OTHER_SEL_END_OFFSET 0x280

#define REG_PINMUX_EXITEN0_OFFSET 0x284
#define REG_PINMUX_EXITEDGE0_OFFSET 0x288
#define REG_PINMUX_EXITINV0_OFFSET 0x28C
#define REG_PINMUX_HOLD_OFFSET 0x290

_Static_assert(REG_PINMUX_REG_COUNT * 4 == REG_PINMUX_HOLD_OFFSET + 4,
               "PINMUX register file must end at HOLD");

Component *PINMUX_Initialize(void);

#endif /* H1B3C_PERIPHERALS_PINMUX_H */
